export const _STR = STR;

export const Lang = {
  get: () => lang,
  set(l) {
    if (LANGS.includes(l)) {
      lang = l;
      localStorage.setItem(KEY, l);
    }
  },
  cycle() {
    this.set(LANGS[(LANGS.indexOf(lang) + 1) % LANGS.length]);
    return lang;
  }
};
